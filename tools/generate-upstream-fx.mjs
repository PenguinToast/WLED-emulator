import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = new URL("../", import.meta.url);
const vendorWledPath = "vendor/WLED";
const fxPath = new URL(`../${vendorWledPath}/wled00/FX.cpp`, import.meta.url);
const headerPath = new URL(`../${vendorWledPath}/wled00/FX.h`, import.meta.url);
const outDir = new URL("../cpp_harness/generated/", import.meta.url);
const outPath = new URL("./upstream_fx_1d.cpp", outDir);
const headerOutPath = new URL("./upstream_fx_1d.hpp", outDir);
const manifestOutPath = new URL("./upstream_fx_1d_modes.json", outDir);

export async function generateUpstreamFx() {
  const [source, header] = await Promise.all([
    readFile(fxPath, "utf8"),
    readFile(headerPath, "utf8"),
  ]);
  const modeDefines = [...header.matchAll(/^#define\s+(FX_MODE_[A-Z0-9_]+)\s+(\d+)/gm)]
    .map((match) => `#ifndef ${match[1]}\n#define ${match[1]} ${match[2]}\n#endif`)
    .join("\n");

  const start = source.indexOf("#define IBN");
  const end = source.indexOf("\nuint8_t WS2812FX::addEffect(");
  if (start < 0 || end < 0 || end <= start) {
    throw new Error("Could not find extract bounds in vendored FX.cpp");
  }

  let body = source.slice(start, end);
  body = body.replace(/static const char _data_[^;]+;\n/g, "");
  body = body.replace(/\bstatic\s+void\s+(mode_[A-Za-z0-9_]+)\s*\(/g, "void $1(");
  body = body.replace(/CRGBPalette16 targetPalette = SEGPALETTE;/g, "CRGBPalette16 targetPalette;");
  body = body.replace(/CRGBPalette16& palette = SEGPALETTE;/g, "CRGBPalette16 palette;");

  const output = `// Generated by tools/generate-upstream-fx.mjs from ${join(root.pathname, `${vendorWledPath}/wled00/FX.cpp`)}.
// Do not edit by hand.

#include "wled_effect_harness.hpp"

#ifndef PROGMEM
#define PROGMEM
#endif
#ifndef IRAM_ATTR
#define IRAM_ATTR
#endif
#ifndef IRAM_ATTR_YN
#define IRAM_ATTR_YN
#endif
#ifndef WLED_DISABLE_2D
#define WLED_DISABLE_2D
#endif
#ifndef WLED_DISABLE_PARTICLESYSTEM1D
#define WLED_DISABLE_PARTICLESYSTEM1D
#endif
#ifndef WLED_DISABLE_PARTICLESYSTEM2D
#define WLED_DISABLE_PARTICLESYSTEM2D
#endif
#ifndef WLED_PS_DONT_REPLACE_1D_FX
#define WLED_PS_DONT_REPLACE_1D_FX
#endif
#ifndef WLED_PS_DONT_REPLACE_2D_FX
#define WLED_PS_DONT_REPLACE_2D_FX
#endif
#ifndef ESP32
#define ESP32
#endif
#ifndef FX_FALLBACK_STATIC
#define FX_FALLBACK_STATIC { mode_static(); return; }
#endif
#ifndef paletteBlend
#define paletteBlend strip.paletteBlend
#endif

${modeDefines}

${body}
`;

  const definedFunctions = new Set([...body.matchAll(/(?:^|\n)void\s+(mode_[A-Za-z0-9_]+)\s*\(/g)].map((match) => match[1]));
  const dispatchEntries = [["FX_MODE_STATIC", "mode_static"], ...source.matchAll(/addEffect\((FX_MODE_[A-Z0-9_]+),\s*&?(mode_[A-Za-z0-9_]+),/g).map((match) => [match[1], match[2]])]
    .filter((entry) => !entry[0].startsWith("FX_MODE_2D"))
    .filter((entry) => !entry[0].startsWith("FX_MODE_PARTICLE") && !entry[0].startsWith("FX_MODE_PS"))
    .filter((entry) => definedFunctions.has(entry[1]));
  const declarations = [...new Set(dispatchEntries.map((entry) => entry[1]))]
    .map((name) => `void ${name}(void);`)
    .join("\n");
  const cases = dispatchEntries
    .map((entry) => `    case ${entry[0]}: return &${entry[1]};`)
    .join("\n");
  const modeIdByName = new Map(
    [...header.matchAll(/^#define\s+(FX_MODE_[A-Z0-9_]+)\s+(\d+)/gm)]
      .map((match) => [match[1], Number(match[2])]),
  );
  const supportedModes = dispatchEntries
    .map(([name, fn]) => ({ id: modeIdByName.get(name), name, function: fn }))
    .filter((entry) => Number.isInteger(entry.id))
    .sort((a, b) => a.id - b.id);
  const headerOutput = `// Generated by tools/generate-upstream-fx.mjs. Do not edit by hand.
#pragma once

#include "wled_effect_harness.hpp"

using UpstreamModePtr = void (*)();

${modeDefines}

${declarations}

inline UpstreamModePtr upstreamModeFor(uint8_t mode) {
  switch (mode) {
${cases}
    default: return nullptr;
  }
}
`;
  const manifestOutput = `${JSON.stringify({
    generatedFrom: `${vendorWledPath}/wled00/FX.cpp`,
    excludes: ["2D/matrix modes"],
    modeCount: supportedModes.length,
    modes: supportedModes,
  }, null, 2)}\n`;

  await mkdir(outDir, { recursive: true });
  await writeFile(outPath, output);
  await writeFile(headerOutPath, headerOutput);
  await writeFile(manifestOutPath, manifestOutput);
  return outPath;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const generated = await generateUpstreamFx();
  console.log(generated.pathname);
}
